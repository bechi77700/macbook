"""
Pictogrammes vectoriels au trait, dessines dans un carre normalise -1..1.
Trait fin regulier, formes simplifiees pour rester lisibles a 6-8 mm.
"""

def wrap(cx, cy, r, inner, px_to_mm, stroke="#FFFFFF", sw_px=1.15, opacity=0.92):
    """Place un dessin normalise dans le cercle de centre (cx,cy) et rayon r."""
    k = r * px_to_mm * 0.60
    return (f'<g transform="translate({cx:.3f},{cy:.3f}) scale({k:.4f})" '
            f'fill="none" stroke="{stroke}" stroke-width="{(sw_px*px_to_mm)/k:.4f}" '
            f'stroke-linecap="round" stroke-linejoin="round" opacity="{opacity}">'
            f'{inner}</g>')


